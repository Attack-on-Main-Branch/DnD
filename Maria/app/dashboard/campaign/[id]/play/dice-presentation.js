/**
 * Which colour a roll is in, and the one place that is decided.
 *
 * Two casts, gold and arcane violet, and everything downstream reads them off
 * four custom properties rather than branching on `secret` again — the rail's
 * glyphs, the arena's rim, the bloom under both and the banner at the end are
 * all one set of literal classes with these swapped underneath. A class built
 * from a template is a class Tailwind's scanner never sees, so the alternative
 * would be two of everything.
 *
 * The switch is meant to be instant: an unregistered custom property changes in
 * one step rather than interpolating, so the whole rail turns over on the same
 * frame the toggle does. The transitions that DO run — a hover bloom, the
 * arena's unfold — read whichever value is standing at the time.
 *
 * `theme` names a folder under `public/assets/dice-box/themes`, generated by
 * scripts/dice-assets.mjs from the same DICE_THEMES this imports. Both casts
 * are cut from the same obsidian; only the pigment on the numerals changes,
 * because the house rolls one set of dice whether or not the table may read
 * them. A PLAYER's dice are that same set repainted — see `diceMaterial`.
 */

import { diceColorHex } from "@/app/dashboard/character-presentation";
import { DICE_THEMES } from "@/lib/dice-themes";

const CASTS = {
  /*
   * `rest` and `ink` are a mark untouched and a mark under the pointer, and
   * they are always two different values — the rail has to answer to a pointer
   * whichever colour it is wearing. In the open, resting is the same
   * `text-ink/60` every other mark in the app rests at and only the lit state
   * is the accent; kept, both are the accent and the resting one is dimmed to
   * the same distance below it.
   */
  open: {
    theme: "obsidian",
    style: {
      "--cast-rest": "var(--ink-60)",
      "--cast-ink": "var(--color-gold)",
      "--cast-rule": "var(--gold-60)",
      // Nothing: the glass mat's own gold hairline is the resting edge.
      "--cast-idle": "transparent",
      "--cast-rim": "var(--gold-70)",
      "--cast-ring": "var(--gold-25)",
      "--cast-line": "var(--gold-35)",
      "--cast-wash": "var(--gold-12)",
      "--cast-bloom": "var(--gold-55)",
    },
  },

  secret: {
    theme: "amethyst",
    style: {
      "--cast-rest": "var(--arcane-55)",
      "--cast-ink": "var(--color-arcane)",
      "--cast-rule": "var(--arcane-55)",
      // Strong enough to carry over the mat's gold hairline underneath it,
      // which is still there and cannot be taken away from a client component.
      "--cast-idle": "var(--arcane-40)",
      "--cast-rim": "var(--arcane-70)",
      "--cast-ring": "var(--arcane-30)",
      "--cast-line": "var(--arcane-30)",
      "--cast-wash": "var(--arcane-15)",
      "--cast-bloom": "var(--arcane-55)",
    },
  },
};

/* Fails the build rather than a roll: a theme renamed in one file and not the
   other would otherwise show up as a die that never arrives. */
for (const cast of Object.values(CASTS)) {
  if (!DICE_THEMES[cast.theme]) {
    throw new Error(`No dice theme generated for "${cast.theme}".`);
  }
}

export function diceCast(secret) {
  return secret ? CASTS.secret : CASTS.open;
}

/**
 * WHAT ONE THROW IS MADE OF: which lettering, and what the body is cast in.
 *
 * The lettering is the cast's — gold in the open, violet behind the veil — and
 * it comes off a generated texture, which is why there are two of those and
 * only two. The BODY is a runtime argument, so a player's twelve colours cost
 * nothing but a string.
 *
 * `color` is the roller's own slug, and null says the house's dice: the head of
 * the table has no character and therefore no colour of their own. A kept roll
 * takes the house's body too — a secret roll is the head of the table's by
 * definition, and 20260919090000 gives nobody else a way to make one.
 */
export function diceMaterial({ secret = false, color = null } = {}) {
  const { theme } = diceCast(secret);

  return {
    theme,
    themeColor:
      secret || !color ? DICE_THEMES[theme].body : diceColorHex(color),
  };
}

/** dice-box's own notation, for however many of one die the rail was set to. */
export function dieNotation(id, count) {
  return `${count}${id}`;
}

/** The same throw as a table names it: "d20", "3d6". */
export function diceName(id, count) {
  return count > 1 ? `${count}${id}` : id;
}

/** What the pill says while the die is still on its way to a number. */
export const ROLLING_LABEL = "Rolling…";

/**
 * What the banner and the ledger say. The wording is Maria's, as always: Sina
 * knows a die has twenty faces and nothing about how to announce one.
 */
export function rollSentence({ die, count, value, secret }) {
  return `${secret ? "Secret roll: " : ""}${diceName(die, count)} ➔ ${value}`;
}
